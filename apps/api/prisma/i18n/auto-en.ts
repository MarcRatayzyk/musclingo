function replaceWords(input: string): string {
  return input.replace(
    /\b[0-9A-Za-zÀ-ÖØ-öø-ÿ'’-]+\b/g,
    (token: string): string => {
      const key = token.toLowerCase();
      const replacement = WORDS[key];
      if (!replacement) return token;
      if (token[0] && token[0] === token[0].toUpperCase()) {
        return replacement.charAt(0).toUpperCase() + replacement.slice(1);
      }
      return replacement;
    },
  );
}

function cleanup(text: string): string {
  return text
    .replace(/\s+([,.;:!?])/g, "$1")
    .replace(/\.{2,}/g, ".")
    .replace(/\(\s+/g, "(")
    .replace(/\s+\)/g, ")")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([’'])\s+/g, "$1")
    .trim();
}

function looksMostlyEnglish(text: string): boolean {
  const frenchHits =
    (text.match(
      /\b(le|la|les|un|une|des|du|de|et|est|sont|dans|pour|avec|sans|que|qui|une|pas|plus|tout|cette|ces)\b/gi,
    )?.length ?? 0) + (text.match(/[àâäéèêëïîôùûüçœ]/gi)?.length ?? 0);
  return frenchHits <= 1;
}

function translateInline(fr: string): string {
  const trimmed = fr.trim();
  const exact = EXACT_EN[trimmed];
  if (exact) return exact;

  let out = fr;
  for (const [pattern, replacement] of PHRASES) {
    out = out.replace(pattern, replacement);
  }
  out = replaceWords(out);
  out = cleanup(out);

  if (out !== trimmed) return out;
  if (looksMostlyEnglish(trimmed)) return trimmed;
  return out;
}

export function enOrTranslate(fr: string): string {
  if (!fr) return fr;
  return fr
    .split("\n")
    .map((line) => {
      if (!line.trim()) return line;
      // Preserve markdown bold markers while translating inner text lightly
      const markerMatch = line.match(
        /^(\s*[-*]\s+|\s*\d+\.\s+|#+\s+|>\s+)?(.*)$/,
      );
      if (!markerMatch) return translateInline(line);
      const marker = markerMatch[1] ?? "";
      const content = markerMatch[2] ?? "";
      if (!content.trim()) return line;
      return `${marker}${translateInline(content)}`;
    })
    .join("\n");
}
